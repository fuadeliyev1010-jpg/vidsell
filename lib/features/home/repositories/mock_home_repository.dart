  static FeedItem _feedItem({
    required String id,
    required String title,
    required double price,
    required String currency,
    required String sellerName,
    required String sellerHandle,
    required String sellerId,
    required String city,
    required String cityId,
    required String categoryId,
    required String categoryLabel,
    required String subcategoryId,
    required String subcategoryLabel,
    required double latitude,
    required double longitude,
    required String shareUrl,
  }) {
    final product = Product(
      id: id,
      title: title,
      price: price,
      currency: currency,
      imageUrls: const [_thumbnailUrl],
      categoryId: categoryId,
      categoryLabel: categoryLabel,
      subcategoryId: subcategoryId,
      subcategoryLabel: subcategoryLabel,
      city: city,
      cityId: cityId,
      sellerId: sellerId,
      sellerName: sellerName,
      sellerHandle: sellerHandle,
      shareUrl: shareUrl,
      latitude: latitude,
      longitude: longitude,
      createdAt: DateTime.utc(2026, 1, 1),
    );
    return FeedItem(
      videoId: 'video-$id',
      thumbnailUrl: _thumbnailUrl,
      hlsUrl: _videoUrl,
      rawUrl: _videoUrl,
      durationSeconds: 30,
      contentType: FeedContentType.recent,
      products: [product],
      createdAt: product.createdAt,
      ownerId: sellerId,
      ownerName: sellerName,
      ownerAvatarUrl: product.sellerAvatarUrl,
    );
  }

  @override
  Future<PageResponse<FeedItem>> fetchListings({
    int page = 1,
    int size = 5,
    String? categoryId,
    String? subcategoryId,
    String? cityId,
    String? sellerId,
    FeedTab tab = FeedTab.forYou,
    double? latitude,
    double? longitude,
    SellerType? sellerType,
  }) async {
    final start = (page - 1) * size;
    final userListings =
        await userListingRepository?.fetchMyListings(
          status: ProductStatus.active,
        ) ??
        const [];
    final allListings = [
      ...userListings.map(_feedItemFromProduct),
      ..._listings,
    ];
    final listings = allListings.where((item) {
      final product = item.product;
      if (product == null) {
        return categoryId == null &&
            subcategoryId == null &&
            cityId == null &&
            sellerId == null;
      }
      if (categoryId != null && product.categoryId != categoryId) return false;
      if (subcategoryId != null && product.subcategoryId != subcategoryId) {
        return false;
      }
      if (cityId != null && product.cityId != cityId) return false;
      if (sellerId != null && product.sellerId != sellerId) return false;
      return true;
    }).toList(growable: false);
    final end = (start + size).clamp(0, listings.length);
    final items = listings.sublist(start, end);
    return PageResponse(
      items: items,
      page: page - 1,
      size: items.length,
      totalElements: listings.length,
      totalPages: (listings.length / size).ceil(),
      last: end >= listings.length,
    );
  }

  static FeedItem _feedItemFromProduct(Product product) => FeedItem(
    videoId: 'video-${product.id}',
    thumbnailUrl: product.imageUrls.isEmpty ? null : product.imageUrls.first,
    hlsUrl: _videoUrl,
    rawUrl: _videoUrl,
    durationSeconds: 30,
    contentType: FeedContentType.recent,
    products: [product],
    createdAt: product.createdAt,
    ownerId: product.sellerId,
    ownerName: product.sellerName,
    ownerAvatarUrl: product.sellerAvatarUrl,
  );
}
